/** Übersetzt einen deutschen Text; unbekannte Texte bleiben unverändert. */
const fragCache = new Map<string, string>();
export function t(s: string): string {
  if (current !== 'en') return s;
  const hit = en[s];
  if (hit !== undefined) return hit;
  let r = fragCache.get(s);
  if (r === undefined) { r = fragments(s); if (fragCache.size > 2000) fragCache.clear(); fragCache.set(s, r); }
  return r;
}

/** Zusammengesetzte Meldungen („Modell X: Download läuft bereits“, mehrzeilige Fehler): bekannte Satzteile einzeln übersetzen, Rest bleibt. */
let fragmentList: [string, string][] | null = null;
function fragments(s: string): string {
  if (!s || s.length < 6) return s;
  fragmentList ??= Object.entries(en).filter(([k]) => k.length >= 8 && !k.includes('{{')).sort((a, b) => b[0].length - a[0].length);
  let out = s;
  for (const [k, v] of fragmentList) if (out.includes(k)) out = out.split(k).join(v);
  return out;
}
